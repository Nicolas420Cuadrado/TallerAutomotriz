BEGIN;

-- ------------------------------------------------------------
-- Roles
-- ------------------------------------------------------------
CREATE TABLE roles (
    id_rol      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol  VARCHAR(20) NOT NULL,
    CONSTRAINT uk_rol_nombre UNIQUE (nombre_rol),
    CONSTRAINT ck_rol_nombre CHECK (nombre_rol IN ('ADMINISTRADOR', 'MECANICO'))
);

-- ------------------------------------------------------------
-- Modelos de vehiculo
-- ------------------------------------------------------------
CREATE TABLE modelos (
    id_modelo      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca          VARCHAR(60) NOT NULL,
    nombre_modelo  VARCHAR(80) NOT NULL,
    estado_modelo  BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_modelo_marca_nombre UNIQUE (marca, nombre_modelo)
);

-- ------------------------------------------------------------
-- Usuarios del sistema
-- ------------------------------------------------------------
CREATE TABLE usuarios (
    id_usuario      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(60)  NOT NULL,
    apellido        VARCHAR(60)  NOT NULL,
    email           VARCHAR(120) NOT NULL,
    username        VARCHAR(40)  NOT NULL,
    clave           VARCHAR(100) NOT NULL,
    estado_usuario  BOOLEAN NOT NULL DEFAULT TRUE,
    id_rol          BIGINT NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT uk_usuario_username UNIQUE (username),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES roles (id_rol)
);

-- ------------------------------------------------------------
-- Vehiculos (el dueno se modela como atributos del vehiculo)
-- ------------------------------------------------------------
CREATE TABLE vehiculos (
    id_vehiculo      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa            VARCHAR(7)  NOT NULL,
    color_placa      VARCHAR(10) NOT NULL,
    nombre_dueno     VARCHAR(80) NOT NULL,
    documento_dueno  VARCHAR(20) NOT NULL,
    telefono_dueno   VARCHAR(20) NOT NULL,
    id_modelo        BIGINT NOT NULL,
    estado_vehiculo  BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_vehiculo_placa UNIQUE (placa),
    CONSTRAINT ck_vehiculo_placa_formato CHECK (placa ~ '^[A-Z]{3}-[0-9]{3}$'),
    CONSTRAINT ck_vehiculo_color CHECK (color_placa IN ('AMARILLA', 'BLANCA')),
    CONSTRAINT fk_vehiculo_modelo FOREIGN KEY (id_modelo) REFERENCES modelos (id_modelo)
);

-- ------------------------------------------------------------
-- Repuestos
-- ------------------------------------------------------------
CREATE TABLE repuestos (
    id_repuesto      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    descripcion      VARCHAR(255),
    precio           NUMERIC(12,2) NOT NULL,
    ean              VARCHAR(13) NOT NULL,
    stock            INTEGER NOT NULL,
    imagen_url       VARCHAR(500),
    estado_repuesto  BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_repuesto_ean UNIQUE (ean),
    CONSTRAINT ck_repuesto_precio CHECK (precio > 0),
    CONSTRAINT ck_repuesto_stock CHECK (stock >= 0),
    CONSTRAINT ck_repuesto_ean_formato CHECK (ean ~ '^[0-9]{13}$')
);

-- ------------------------------------------------------------
-- Relacion muchos a muchos: repuestos compatibles por modelo
-- ------------------------------------------------------------
CREATE TABLE repuesto_modelo (
    id_repuesto  BIGINT NOT NULL,
    id_modelo    BIGINT NOT NULL,
    CONSTRAINT pk_repuesto_modelo PRIMARY KEY (id_repuesto, id_modelo),
    CONSTRAINT fk_repuesto_modelo_repuesto FOREIGN KEY (id_repuesto)
        REFERENCES repuestos (id_repuesto) ON DELETE CASCADE,
    CONSTRAINT fk_repuesto_modelo_modelo FOREIGN KEY (id_modelo)
        REFERENCES modelos (id_modelo) ON DELETE CASCADE
);

-- ------------------------------------------------------------
-- Reparaciones
-- ------------------------------------------------------------
CREATE TABLE reparaciones (
    id_reparacion         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha                 DATE NOT NULL,
    tipo                  VARCHAR(30) NOT NULL,
    estado                VARCHAR(20) NOT NULL DEFAULT 'EN_PROCESO',
    id_vehiculo           BIGINT NOT NULL,
    id_usuario_mecanico   BIGINT NOT NULL,
    observaciones         VARCHAR(500),
    CONSTRAINT ck_reparacion_tipo CHECK (tipo IN (
        'MANTENIMIENTO_PREVENTIVO',
        'REPARACION_CORRECTIVA',
        'REVISION',
        'OTRO'
    )),
    CONSTRAINT ck_reparacion_estado CHECK (estado IN (
        'EN_PROCESO',
        'TERMINADO',
        'CANCELADO'
    )),
    CONSTRAINT fk_reparacion_vehiculo FOREIGN KEY (id_vehiculo)
        REFERENCES vehiculos (id_vehiculo),
    CONSTRAINT fk_reparacion_mecanico FOREIGN KEY (id_usuario_mecanico)
        REFERENCES usuarios (id_usuario)
);

-- ------------------------------------------------------------
-- Indices de apoyo para busquedas
-- ------------------------------------------------------------
CREATE INDEX idx_repuesto_nombre ON repuestos (nombre);
CREATE INDEX idx_reparacion_estado ON reparaciones (estado);
CREATE INDEX idx_reparacion_mecanico ON reparaciones (id_usuario_mecanico);
CREATE INDEX idx_reparacion_fecha ON reparaciones (fecha);

COMMIT;
